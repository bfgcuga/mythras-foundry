export function withCreatureArt(source) {
  const family = source.name.replace(/ \((?:\d+ m³|TAM \d+)\)$/, "");
  const img = CREATURE_ART[family];
  if (!img) return source;
  return { ...source, img, prototypeToken: { ...source.prototypeToken,
    texture: { ...source.prototypeToken.texture, src: img } } };
}
